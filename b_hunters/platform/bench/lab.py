"""The vulnerable application laboratory.

The lab is a separate Docker Compose project on its own bridge network.
Every application binds to ``127.0.0.1`` on the host, so the lab is never
reachable from an untrusted network, and the platform's own containers
reach it through the internal network name.

The lab is *never* started automatically.  The operator starts it
explicitly with ``b-hunters bench lab up`` and stops it with
``b-hunters bench lab down``.
"""

from __future__ import annotations

import json
import os
import shutil
import socket
import subprocess
import time
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Optional

from .manifest import BenchmarkApplication, default_manifests

#: The compose project name, so the lab is clearly separated from anything else.
LAB_PROJECT = "bhunters-bench"

#: The isolated network name.
LAB_NETWORK = "bhunters-bench-net"

#: The host directory that holds the generated compose file.
LAB_DIR = Path(os.environ.get("BHUNTERS_BENCH_DIR", "/var/lib/b-hunters/bench"))

COMPOSE_TEMPLATE = """\
# B-Hunters vulnerable application laboratory.
#
# Generated by `b-hunters bench lab up`.  Every port is published on
# 127.0.0.1 only, and the applications share a dedicated bridge network so
# that they cannot reach anything else on the host.
version: "3.8"

networks:
  {network}:
    name: {network}
    driver: bridge
    internal: false

services:
{services}
"""


@dataclass
class LabStatus:
    """The state of the laboratory."""

    running: bool
    applications: list[dict[str, Any]]
    network: str = LAB_NETWORK
    compose_path: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "running": self.running,
            "applications": self.applications,
            "network": self.network,
            "compose_path": self.compose_path,
        }


class LabManager:
    """Manages the laboratory containers."""

    def __init__(self, directory: Optional[Path] = None) -> None:
        self.directory = Path(directory or LAB_DIR)
        self.compose_path = self.directory / "docker-compose.bench.yml"

    # ------------------------------------------------------------------
    def manifests(self) -> list[BenchmarkApplication]:
        return default_manifests()

    def compose_file(self, slugs: Optional[Sequence[str]] = None) -> str:
        """Render the compose file for the selected applications."""
        wanted = set(slugs) if slugs else None
        blocks: list[str] = []
        for manifest in self.manifests():
            if wanted is not None and manifest.slug not in wanted:
                continue
            blocks.append(self._service_block(manifest))
        if not blocks:
            raise RuntimeError("no benchmark applications were selected")
        return COMPOSE_TEMPLATE.format(network=LAB_NETWORK, services="\n".join(blocks))

    def _service_block(self, manifest: BenchmarkApplication) -> str:
        environment = "".join(f"      {key}: {value}\n" for key, value in manifest.environment.items())
        command = ""
        if manifest.start_command:
            joined = " ".join(manifest.start_command)
            command = f"    command: {json.dumps(joined)}\n"
        published = f"127.0.0.1:{manifest.port}:{manifest.port}"
        ports = f'    ports:\n      - "{published}"\n'
        default_environment = '      BENCH_APP: "1"\n'
        environment_block = environment if environment else default_environment
        healthcheck = self._healthcheck_command(manifest)
        return (
            f"  bench-{manifest.slug}:\n"
            f"    image: {manifest.image}\n"
            f"    container_name: bh-bench-{manifest.slug}\n"
            f'    restart: "no"\n'
            f"{command}{ports}"
            f"    environment:\n{environment_block}"
            f"    networks:\n      - {LAB_NETWORK}\n"
            f"    healthcheck:\n"
            f"      test:\n"
            f"        - CMD-SHELL\n"
            f"        - {healthcheck}\n"
            f"      interval: 10s\n"
            f"      timeout: 8s\n"
            f"      retries: 12\n"
        )

    def _healthcheck_command(self, manifest: BenchmarkApplication) -> str:
        """Build the shell command that probes the application.

        A manifest may declare its own command; the default uses Python's
        standard library, which every Python application image provides.
        """
        if manifest.healthcheck_command:
            return " ".join(manifest.healthcheck_command)
        url = f"http://127.0.0.1:{manifest.port}{manifest.healthcheck_path}"
        return f"python3 -c \"import urllib.request; urllib.request.urlopen('{url}', timeout=5)\""

    # ------------------------------------------------------------------
    def write(self, slugs: Optional[Sequence[str]] = None) -> Path:
        self.directory.mkdir(parents=True, exist_ok=True)
        self.compose_path.write_text(self.compose_file(slugs), encoding="utf-8")
        return self.compose_path

    def up(self, slugs: Optional[Sequence[str]] = None) -> dict[str, Any]:
        """Start the laboratory."""
        if not shutil.which("docker"):
            raise RuntimeError("docker is not installed or not on PATH")
        path = self.write(slugs)
        result = subprocess.run(
            ["docker", "compose", "-p", LAB_PROJECT, "-f", str(path), "up", "-d"],
            capture_output=True,
            text=True,
            timeout=900,
        )
        if result.returncode != 0:
            raise RuntimeError(f"could not start the lab: {result.stderr.strip()[:500]}")
        return {"status": "started", "compose_path": str(path)}

    def down(self) -> dict[str, Any]:
        """Stop and remove the laboratory."""
        if not self.compose_path.exists():
            return {"status": "not_running"}
        subprocess.run(
            [
                "docker",
                "compose",
                "-p",
                LAB_PROJECT,
                "-f",
                str(self.compose_path),
                "down",
                "--remove-orphans",
                "-v",
            ],
            capture_output=True,
            text=True,
            timeout=600,
        )
        return {"status": "stopped"}

    def status(self) -> LabStatus:
        """Report the state of the laboratory."""
        applications: list[dict[str, Any]] = []
        running = False
        if shutil.which("docker") and self.compose_path.exists():
            result = subprocess.run(
                [
                    "docker",
                    "compose",
                    "-p",
                    LAB_PROJECT,
                    "-f",
                    str(self.compose_path),
                    "ps",
                    "--format",
                    "json",
                ],
                capture_output=True,
                text=True,
                timeout=60,
            )
            entries: list[dict[str, Any]] = []
            if result.returncode == 0 and result.stdout.strip():
                try:
                    parsed = json.loads(result.stdout)
                    entries = parsed if isinstance(parsed, list) else [parsed]
                except ValueError:
                    for line in result.stdout.splitlines():
                        line = line.strip()
                        if line.startswith("{"):
                            try:
                                entries.append(json.loads(line))
                            except ValueError:
                                continue
            running = bool(entries)
            for entry in entries:
                name = entry.get("Service") or entry.get("Name", "")
                applications.append(
                    {
                        "slug": name.replace("bench-", ""),
                        "container": entry.get("Name", ""),
                        "state": entry.get("State", ""),
                        "status": entry.get("Status", ""),
                        "ports": entry.get("Publishers", []),
                    }
                )
        return LabStatus(
            running=running,
            applications=applications,
            compose_path=str(self.compose_path),
        )

    # ------------------------------------------------------------------
    def wait_healthy(
        self, manifest: BenchmarkApplication, *, timeout: Optional[int] = None
    ) -> tuple[bool, str]:
        """Wait until an application answers on its port."""
        deadline = time.time() + (timeout if timeout is not None else manifest.startup_seconds)
        while time.time() < deadline:
            if self._port_open("127.0.0.1", manifest.port):
                return True, ""
            time.sleep(1.0)
        return False, f"{manifest.name} did not become ready within the startup window"

    @staticmethod
    def _port_open(host: str, port: int, timeout: float = 1.5) -> bool:
        try:
            with socket.create_connection((host, port), timeout=timeout):
                return True
        except OSError:
            return False

    def cleanup(self) -> dict[str, Any]:
        """Remove the laboratory and its volumes."""
        result = self.down()
        if self.compose_path.exists():
            self.compose_path.unlink()
        return result
